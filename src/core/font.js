export function glyph(ch) {
  return G[ch.toUpperCase()] || G[' '];
}

export function textWidth(text, spacing = 1) {
  return text.length * (5 + spacing) - spacing;
}

// draw(x, y) is called for each lit pixel
export function drawText(text, x0, y0, draw, { spacing = 1, scale = 1 } = {}) {
  let x = x0;
  for (const ch of text) {
    const g = glyph(ch);
    for (let r = 0; r < 7; r++)
      for (let c = 0; c < 5; c++)
        if (g[r][c] === '1')
          for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) draw(x + c * scale + sx, y0 + r * scale + sy);
    x += (5 + spacing) * scale;
  }
  return x - x0 - spacing * scale;
}

// Fictional logograms: radicals made of strokes on a 7x7 grid.
export function pseudoGlyph(seed) {
  const rng = new RNG(seed * 7919 + 13);
  const g = Array.from({ length: 7 }, () => new Array(7).fill(0));
  const hline = (y, x0, x1) => {
    for (let x = x0; x <= x1; x++) g[y][x] = 1;
  };
  const vline = (x, y0, y1) => {
    for (let y = y0; y <= y1; y++) g[y][x] = 1;
  };
  const layout = rng.int(0, 3);
  if (layout === 0) {
    // left radical + right body
    vline(1, rng.int(0, 2), 6);
    if (rng.chance(0.6)) hline(rng.int(1, 3), 0, 2);
    hline(0, 3, 6);
    vline(rng.pick([4, 5]), 0, 6);
    hline(rng.int(2, 4), 3, 6);
    hline(6, 3, 6);
  } else if (layout === 1) {
    // top + bottom
    hline(0, rng.int(0, 2), rng.int(4, 6));
    vline(3, 0, rng.int(2, 3));
    hline(3, 0, 6);
    vline(rng.pick([1, 2]), 3, 6);
    vline(rng.pick([4, 5]), 3, 6);
    hline(6, 1, 5);
  } else if (layout === 2) {
    // enclosure
    hline(0, 0, 6);
    vline(0, 0, 6);
    vline(6, 0, 6);
    hline(6, 0, 6);
    hline(3, 2, 4);
    vline(3, 2, rng.int(4, 5));
  } else {
    // free strokes
    for (let s = 0; s < 5; s++) {
      if (rng.chance(0.5)) {
        const y = rng.int(0, 6);
        hline(y, rng.int(0, 2), rng.int(4, 6));
      } else {
        const x = rng.int(0, 6);
        vline(x, rng.int(0, 2), rng.int(4, 6));
      }
    }
  }
  // a couple of dots / ticks
  for (let i = 0; i < 2; i++) if (rng.chance(0.5)) g[rng.int(0, 6)][rng.int(0, 6)] = 1;
  return g;
}

export function drawPseudo(seed, x0, y0, draw, scale = 1) {
  const g = pseudoGlyph(seed);
  for (let r = 0; r < 7; r++)
    for (let c = 0; c < 7; c++)
      if (g[r][c]) for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) draw(x0 + c * scale + sx, y0 + r * scale + sy);
}
